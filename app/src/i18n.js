// Дата с сервера "2026-10-13" -> "13.10.2026"
export function formatDate(value) {
  if (!value) return '';
  const [year, month, day] = String(value).slice(0, 10).split('-');
  return day && month && year ? `${day}.${month}.${year}` : String(value);
}